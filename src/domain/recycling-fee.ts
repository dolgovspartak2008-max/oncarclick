export const RECYCLING_FEE_TABLE = { UP_TO_2L, UP_TO_3L, UP_TO_35L, OVER_35L };

export type RecyclingFeeInput = {
  engineCc: number | null;
  powerHp: number | null;
  year: number;
  /** Месяц выпуска 1–12, если известен. */
  month?: number | null;
};

export type RecyclingFee = { feeRub: number; ageGroup: "0-3" | "3-5"; tableYear: number };

function volumeTable(engineCc: number | null) {
  // Электромобили и машины без объёма считаем по самой младшей группе — «до 2 литров».
  if (!engineCc || engineCc <= 2_000) return UP_TO_2L;
  if (engineCc <= 3_000) return UP_TO_3L;
  if (engineCc <= 3_500) return UP_TO_35L;
  return OVER_35L;
}

/** Возраст в месяцах на дату расчёта. Если месяц неизвестен — берём середину года. */
export function ageInMonths(year: number, month: number | null | undefined, now: Date) {
  const m = month && month >= 1 && month <= 12 ? month : 7;
  return (now.getFullYear() - year) * 12 + (now.getMonth() + 1 - m);
}

export function calculateRecyclingFee(car: RecyclingFeeInput, now = new Date()): RecyclingFee | null {
  if (!car.year || car.year < 1950) return null;
  if (!car.powerHp || car.powerHp <= 0) return null;
  const young = ageInMonths(car.year, car.month, now) < 36;
  const ageGroup = young ? "0-3" : "3-5";
  const tableYear = Math.min(YEARS[YEARS.length - 1], Math.max(YEARS[0], now.getFullYear()));
  if (car.powerHp < MIN_TABLE_HP) {
    return { feeRub: young ? PREFERENTIAL_FEE_RUB.young : PREFERENTIAL_FEE_RUB.old, ageGroup, tableYear };
  }
  const band = POWER_BANDS_HP.findIndex((upper) => car.powerHp! <= upper);
  const row = volumeTable(car.engineCc)[band];
  const column = (tableYear - YEARS[0]) * 2 + (young ? 0 : 1);
  return { feeRub: row[column], ageGroup, tableYear };
}

/** Достаёт месяц выпуска из полей Trust Encar: «3», «03», «202303», «2023-03», «03.2023». */
export function parseMonth(value: unknown): number | null {
  const text = String(value ?? "").trim();
  if (!text) return null;
  const compact = text.match(/^(\d{4})(\d{2})$/);
  if (compact) return validMonth(Number(compact[2]));
  const dashed = text.match(/^\d{4}[-./](\d{1,2})/);
  if (dashed) return validMonth(Number(dashed[1]));
  const reversed = text.match(/^(\d{1,2})[-./]\d{4}/);
  if (reversed) return validMonth(Number(reversed[1]));
  if (/^\d{1,2}$/.test(text)) return validMonth(Number(text));
  return null;
}
const validMonth = (value: number) => value >= 1 && value <= 12 ? value : null;
